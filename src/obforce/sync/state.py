def _object(value: object, keys: set[str]) -> dict:
    """Require exact wire keys, without defaulting unknown or missing fields."""
    if type(value) is not dict or value.keys() != keys:
        raise ConflictError('Invalid state object structure')
    return value


def _binding(value: object) -> SourceBinding:
    data = _object(value, {'workspace_id', 'mode', 'org_id'})
    result = SourceBinding(**data)
    if result.mode == 'live' and _id(result.org_id, '00D') != result.org_id:
        raise ConflictError('State requires canonical verified org identity')
    return result


def _selection(value: object) -> Selection:
    data = _object(value, {'types', 'include_namespaced', 'full_names'})
    if data['types'] != ['ApexClass'] or type(data['full_names']) is not list:
        raise ConflictError('Invalid state selection')
    return Selection(data['include_namespaced'], tuple(data['full_names']))


def _coverage(value: object) -> Coverage:
    data = _object(value, {'model_schema', 'binding', 'selection', 'inventory', 'audit', 'relationships'})
    if type(data['model_schema']) is not int or data['model_schema'] != const.MODEL_SCHEMA_VERSION:
        raise ConflictError('Unsupported state model schema')
    facets = []
    for name in ('inventory', 'audit', 'relationships'):
        facet = dict(
            _object(data[name], {'status', 'method', 'requested', 'pagination', 'limit_reached', 'api_version', 'warnings'})
        )
        if type(facet['warnings']) is not list:
            raise ConflictError('Invalid state coverage warnings')
        facet['status'] = CoverageStatus(facet['status'])
        facet['warnings'] = tuple(facet['warnings'])
        facets.append(CollectionCoverage(**facet))
    return Coverage(_binding(data['binding']), _selection(data['selection']), *facets)


def _baseline(state: NoteState, region: bytes) -> None:
    """Validate saved generated data independently of current note content."""
    if type(region) is not bytes or len(region) > const.MAX_RENDER_SECTION_BYTES:
        raise ConflictError('Invalid saved generated bytes')
    if hashlib.sha256(region).hexdigest() != state.generated_region_hash:
        raise ConflictError('Saved generated bytes disagree with digest')
    expected = {
        'obforce_id': state.obforce_id,
        'obforce_schema': const.NOTE_SCHEMA_VERSION,
        'sf_type': state.key.metadata_type,
        'sf_full_name': state.key.full_name,
        'sf_namespace': state.key.namespace,
        'sf_source_mode': state.binding.mode,
    }
    for name, value in expected.items():
        if state.generated_properties.get(name) != FieldValue(Availability.NULL if value is None else Availability.VALUE, value):
            raise ConflictError('Saved source identity contradicts baseline')
    for name, allowed in (
        ('sf_lifecycle', {'active', 'missing'}),
        ('sf_dependency_coverage', {s.value for s in CoverageStatus}),
    ):
        field = state.generated_properties.get(name)
        if (
            field is None
            or field.availability != Availability.VALUE
            or type(field.value) is not str
            or field.value not in allowed
        ):
            raise ConflictError('Invalid saved collection or lifecycle baseline')
    # Validate the saved envelope with the accepted bounded parser, never a current note.
    properties = {}
    for name, field in state.generated_properties.items():
        if field.availability == Availability.UNAVAILABLE:
            continue  # Unavailable stays on wire; it cannot match a present note value.
        value = field.value
        if type(value) is int and value.bit_length() > 64:
            raise ConflictError('Saved property exceeds integer bound')
        if type(value) is tuple and (
            len(value) > const.MAX_YAML_LIST_ITEMS or sum(len(v.encode('utf-8')) for v in value) > const.MAX_FRONTMATTER_BYTES
        ):
            raise ConflictError('Saved property exceeds list bound')
        if type(value) is str and len(value.encode('utf-8')) > const.MAX_YAML_SCALAR_BYTES:
            raise ConflictError('Saved property exceeds scalar bound')
        properties[name] = value
    ending = b'\r\n' if b'\r\n' in region else b'\n'
    front = ''.join(f'{json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}\n' for k, v in sorted(properties.items()))
    raw = b'---\n' + front.encode() + b'---\n' + const.GENERATED_START.encode() + ending
    parsed = parse_note(raw + region + const.GENERATED_END.encode() + ending)
    if parsed.region != region:
        raise ConflictError('Invalid saved generated envelope')


@dataclass(frozen=True, repr=False)
class SavedNote:
    """Pair unchanged immutable NoteState with exact previously accepted generated bytes."""

    note: NoteState
    generated_region: bytes

    def __post_init__(self) -> None:
        if not isinstance(self.note, NoteState):
            raise ModelError('Expected immutable note state')
        _path(self.note.path)
        try:
            _baseline(self.note, self.generated_region)
        except UnicodeError:
            raise ConflictError('Unsupported saved baseline encoding') from None

    def canonical(self) -> dict:
        """Return only generated baselines and minimum private note mapping fields."""
        return {'note': self.note.canonical(), 'generated_region': base64.b64encode(self.generated_region).decode('ascii')}


@dataclass(frozen=True, repr=False)
class StateDocument:
    """Hold one bound scope and independent saved coverage without lifecycle decisions."""

    binding: SourceBinding
    selection: Selection
    coverage: Coverage
    notes: tuple[SavedNote, ...] = ()

    def __post_init__(self) -> None:
        if not isinstance(self.binding, SourceBinding) or not isinstance(self.selection, Selection):
            raise ModelError('Expected normalized state binding and selection')
        if not isinstance(self.coverage, Coverage) or type(self.notes) is not tuple:
            raise ModelError('Expected normalized state coverage and immutable notes')
        _binding(self.binding.canonical())
        require_same_source(self.binding, self.coverage.binding)
        if self.binding.mode == 'local' and (
            self.coverage.audit.status != CoverageStatus.UNAVAILABLE
            or self.coverage.audit.requested
            or self.coverage.relationships.status != CoverageStatus.NOT_COLLECTED
            or self.coverage.relationships.requested
        ):
            raise ConflictError('Offline state cannot assert collected audit or relationships')
        if self.selection != self.coverage.selection or len(self.notes) > const.MAX_STATE_NOTES:
            raise ConflictError('State scope or note bound mismatch')
        for saved in self.notes:
            if not isinstance(saved, SavedNote):
                raise ModelError('Expected saved note envelopes')
            note = saved.note
            require_same_source(self.binding, note.binding)
            if (note.key.namespace is not None and not self.selection.include_namespaced) or (
                self.selection.full_names and note.key.full_name not in self.selection.full_names
            ):
                raise ConflictError('Saved component is outside state selection')
        validate_identities((), (saved.note for saved in self.notes))
        _paths({saved.note.key: saved.note.path for saved in self.notes})
        object.__setattr__(self, 'notes', tuple(sorted(self.notes, key=lambda saved: saved.note.key.token)))

    def canonical(self) -> dict:
        """Serialize explicit scope separately from collection outcomes."""
        return {
            'state_schema': const.STATE_SCHEMA_VERSION,
            'binding': self.binding.canonical(),
            'selection': self.selection.canonical(),
            'scope_hash': self.selection.scope_hash(self.binding),
            'coverage': self.coverage.canonical(),
            'notes': [saved.canonical() for saved in self.notes],
        }


def _json_bounds(value: object) -> None:
    """Bound primitives before model construction or recursive canonical serialization."""
    pending, count, text_bytes = [(value, 0)], 0, 0
    while pending:
        item, depth = pending.pop()
        count += 1
        if count > const.MAX_STATE_NODES or depth > const.MAX_STATE_DEPTH:
            raise ConflictError('State exceeds structural bound')
        if type(item) is str:
            size = len(item.encode('utf-8'))
            text_bytes += size
            if text_bytes > const.MAX_STATE_BYTES or size > const.MAX_STATE_TEXT_BYTES:
                raise ConflictError('State exceeds text bound')
        elif item is None or type(item) is bool:
            continue
        elif type(item) is int and item.bit_length() <= 64:
            continue
        elif type(item) is dict and all(type(k) is str for k in item):
            pending.extend((child, depth + 1) for pair in item.items() for child in pair)
        elif type(item) in (list, tuple):
            pending.extend((child, depth + 1) for child in item)
        else:
            raise ConflictError('Unsupported state value type')


def serialize_state(document: StateDocument) -> bytes:
    """Return deterministic bounded UTF-8 bytes; never open or write a file."""
    if not isinstance(document, StateDocument):
        raise ModelError('Expected validated state document')
    if len(document.notes) > const.MAX_STATE_NOTES:
        raise ConflictError('State exceeds note bound')
    _json_bounds(document.selection.canonical())
    _json_bounds(document.coverage.canonical())
    # Bound each entry before constructing the aggregate object/base64 output.
    value = {
        'state_schema': const.STATE_SCHEMA_VERSION,
        'binding': document.binding.canonical(),
        'selection': document.selection.canonical(),
        'scope_hash': document.selection.scope_hash(document.binding),
        'coverage': document.coverage.canonical(),
        'notes': [],
    }
    estimate = 0
    for saved in document.notes:
        entry = saved.canonical()
        _json_bounds(entry)
        estimate += len(json.dumps(entry, ensure_ascii=False, separators=(',', ':')).encode('utf-8'))
        if estimate > const.MAX_STATE_BYTES:
            raise ConflictError('State exceeds output byte bound')
        value['notes'].append(entry)
    _json_bounds(value)
    chunks, size = [], 1
    encoder = json.JSONEncoder(ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False)
    for chunk in encoder.iterencode(value):
        encoded = chunk.encode('utf-8')
        size += len(encoded)
        if size > const.MAX_STATE_BYTES:
            raise ConflictError('State exceeds output byte bound')
        chunks.append(encoded)
    return b''.join(chunks) + b'\n'


def _pairs(pairs: list[tuple[str, object]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ConflictError('Duplicate state JSON key')
        result[key] = value
    return result


def _lexical_depth(text: str) -> None:
    """Refuse deeply nested JSON before handing it to the recursive decoder."""
    depth, quoted, escaped = 0, False, False
    for char in text:
        if quoted:
            if escaped:
                escaped = False
            elif char == '\\':
                escaped = True
            elif char == '"':
                quoted = False
        elif char == '"':
            quoted = True
        elif char in '[{':
            depth += 1
            if depth > const.MAX_STATE_DEPTH:
                raise ConflictError('State exceeds nesting bound')
        elif char in ']}':
            depth -= 1


def _saved(value: object) -> SavedNote:
    data = _object(value, {'note', 'generated_region'})
    note = dict(
        _object(
            data['note'],
            {
                'state_schema',
                'obforce_id',
                'binding',
                'key',
                'path',
                'source_hash',
                'graph_hash',
                'render_hash',
                'generated_properties',
                'generated_region_hash',
            },
        )
    )
    note['schema_version'] = note.pop('state_schema')
    note['binding'] = _binding(note['binding'])
    key = note['key']
    if type(key) is not list or len(key) != 4 or key[2] == '':
        raise ConflictError('Invalid canonical state component key')
    note['key'] = ComponentKey(*key)
    if type(note['generated_properties']) is not dict:
        raise ConflictError('Invalid saved property mapping')
    fields = {}
    for name, field in note['generated_properties'].items():
        field = _object(field, {'availability', 'value'})
        payload = tuple(field['value']) if type(field['value']) is list else field['value']
        fields[name] = FieldValue(Availability(field['availability']), payload)
    note['generated_properties'] = fields
    encoded = data['generated_region']
    if type(encoded) is not str:
        raise ConflictError('Invalid generated byte encoding')
    region = base64.b64decode(encoded, validate=True)
    if base64.b64encode(region).decode('ascii') != encoded:
        raise ConflictError('Noncanonical generated byte encoding')
    return SavedNote(NoteState(**note), region)


def parse_state(raw: bytes) -> StateDocument:
    """Validate untrusted wire bytes without coercion, adoption, migration or repair.

    :raises ConflictError: For corrupt/unsupported/excessive or contradictory state.
    :raises ModelError: For a non-byte caller input.
    """
    if type(raw) is not bytes:
        raise ModelError('Expected immutable state bytes')
    if not raw or len(raw) > const.MAX_STATE_BYTES:
        raise ConflictError('Invalid state byte bound')
    try:
        text = raw.decode('utf-8')
        _lexical_depth(text)
        data = json.loads(text, object_pairs_hook=_pairs)
        _json_bounds(data)
        data = _object(data, {'state_schema', 'binding', 'selection', 'scope_hash', 'coverage', 'notes'})
        if type(data['state_schema']) is not int or data['state_schema'] != const.STATE_SCHEMA_VERSION:
            raise ConflictError('Unsupported state schema')
        binding, selection = _binding(data['binding']), _selection(data['selection'])
        if data['scope_hash'] != selection.scope_hash(binding) or type(data['notes']) is not list:
            raise ConflictError('Invalid state scope evidence')
        if len(data['notes']) > const.MAX_STATE_NOTES:
            raise ConflictError('State exceeds note bound')
        return StateDocument(binding, selection, _coverage(data['coverage']), tuple(_saved(x) for x in data['notes']))
    except (ConfigError, ValueError, TypeError, KeyError, UnicodeError, RecursionError, binascii.Error):
        raise ConflictError('Invalid or unsupported private state') from None


def _absolute(path: Path) -> None:
    if (
        not isinstance(path, Path)
        or not path.is_absolute()
        or '..' in path.parts
        or len(str(path)) > 32_768
        or len(path.parts) > 256
    ):
        raise ModelError('Expected explicit absolute read path')


def _stamp(info: os.stat_result) -> tuple[int, ...]:
    return (info.st_dev, info.st_ino, info.st_mode, info.st_nlink, info.st_size, info.st_mtime_ns, info.st_ctime_ns)


def _cross_api_stamp(info: os.stat_result, *, windows: bool = os.name == 'nt') -> tuple[int, ...]:
    """Compare timestamps with the same meaning across pathname/descriptor APIs.

    Windows pathname ctime can mean creation while descriptor ctime means change
    time. Require explicit birthtime for that comparison. Repeated observations
    through the same API still use the full ctime-bearing stamp; POSIX is unchanged.
    """
    stamp = _stamp(info)
    if not windows:
        return stamp
    birthtime = getattr(info, 'st_birthtime_ns', None)
    if type(birthtime) is not int:
        raise ConflictError('Required read creation time is unavailable')
    return (*stamp[:-1], birthtime)


def _safe(info: os.stat_result) -> None:
    if stat.S_ISLNK(info.st_mode) or getattr(info, 'st_file_attributes', 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT:
        raise ConflictError('Unsafe read path link or reparse point')
    if not (stat.S_ISDIR(info.st_mode) or (stat.S_ISREG(info.st_mode) and info.st_nlink == 1)):
        raise ConflictError('Unsafe read path type or hard link')


class _Reader:
    """Track finite read observations and recheck the whole snapshot before return."""

    def __init__(self) -> None:
        self.snapshots: dict[Path, tuple[int, ...] | None] = {}
        self.total = 0

    def observe(self, path: Path, *, missing: bool = False) -> os.stat_result | None:
        try:
            info = path.lstat()
        except FileNotFoundError:
            if not missing:
                raise ConflictError('Expected read path vanished') from None
            info = None
        if info is not None:
            _safe(info)
        stamp = _stamp(info) if info is not None else None
        if path in self.snapshots and self.snapshots[path] != stamp:
            raise ConflictError('Read path changed during observation')
        self.snapshots[path] = stamp
        return info

    def parents(self, path: Path) -> None:
        for parent in reversed(path.parents):
            info = self.observe(parent)
            if info is None or not stat.S_ISDIR(info.st_mode):
                raise ConflictError('Read parent is not a directory')

    def read(self, path: Path, limit: int) -> bytes:
        self.parents(path)
        before = self.observe(path)
        if before is None or not stat.S_ISREG(before.st_mode) or before.st_size > limit:
            raise ConflictError('Invalid read file or byte bound')
        if self.total + before.st_size > const.MAX_VAULT_READ_BYTES:
            raise ConflictError('Vault exceeds aggregate read bound')
        flags = os.O_RDONLY | getattr(os, 'O_BINARY', 0) | getattr(os, 'O_NOFOLLOW', 0) | getattr(os, 'O_NONBLOCK', 0)
        with os.fdopen(os.open(path, flags), 'rb') as stream:
            descriptor = os.fstat(stream.fileno())
            _safe(descriptor)
            if _cross_api_stamp(before) != _cross_api_stamp(descriptor):
                raise ConflictError('Read descriptor changed')
            raw = stream.read(limit + 1)
            after = os.fstat(stream.fileno())
            _safe(after)
            if (
                _stamp(descriptor) != _stamp(after)
                or _cross_api_stamp(descriptor) != _cross_api_stamp(after)
                or len(raw) != before.st_size
            ):
                raise ConflictError('Read file changed or exceeded bound')
        self.total += len(raw)
        self.observe(path)
        return raw

    def finish(self) -> None:
        for path in tuple(self.snapshots):
            self.observe(path, missing=self.snapshots[path] is None)


def load_state(path: Path) -> StateDocument | None:
    """Read one explicit state file; return None only for an actually absent document."""
    _absolute(path)
    reader = _Reader()
    try:
        # Inspect every existing ancestor; never create a missing control directory.
        for parent in (*reversed(path.parents), path):
            if reader.observe(parent, missing=True) is None:
                reader.finish()
                return None
            if parent != path and not stat.S_ISDIR(reader.observe(parent).st_mode):
                raise ConflictError('Invalid state parent')
        result = parse_state(reader.read(path, const.MAX_STATE_BYTES))
        reader.finish()
        return result
    except OSError:
        raise OperationalError('Cannot read explicit private state') from None


def _portable(path: str) -> str:
    if len(path) > const.MAX_RENDER_PATH_CHARS or len(path.split('/')) > const.MAX_RENDER_PATH_DEPTH:
        raise ConflictError('Vault path exceeds bound')
    if any(
        len(p.encode('utf-8')) > 240 or any(unicodedata.category(c) in {'Cf', 'Zl', 'Zp'} for c in p) for p in path.split('/')
    ):
        raise ConflictError('Unsafe portable vault path')
    try:
        relative_path(path)
    except ConfigError:
        raise ConflictError('Unsafe portable vault path') from None
    return unicodedata.normalize('NFC', path).casefold()


@dataclass(frozen=True, repr=False)
class PathChange:
    """Supply explicit endpoint path invalidation inputs without changing saved hashes."""

    key: ComponentKey
    old_path: str
    new_path: str


@dataclass(frozen=True, repr=False)
class Reconciliation:
    """Return deterministic immutable candidate state/paths and current parsed observations."""

    state: StateDocument | None
    paths: Mapping[ComponentKey, str]
    path_changes: tuple[PathChange, ...]
    observations: Mapping[str, ParsedNote]
    initial: bool


def reconcile_vault(
    vault: Path,
    state_path: Path,
    binding: SourceBinding,
    selection: Selection,
    *,
    excluded_roots: tuple[Path, ...],
    initial: bool = False,
) -> Reconciliation:
    """Read a bounded explicit vault and accept only uniquely mapped unchanged baselines.

    :param excluded_roots: Explicit source/template/application roots that must be disjoint.
    :param initial: Permit missing state only when the managed scope is genuinely empty.
    :returns: In-memory candidate path changes; never publishes or infers source absence.
    :raises ConflictError: For unsafe paths, incomplete scans, ownership or baseline conflicts.
    :raises OperationalError: For unreadable files/directories.
    """
    _absolute(vault)
    _absolute(state_path)
    if state_path != vault / '.obforce' / 'state.json':
        raise ModelError('Expected explicit vault state document')
    if not isinstance(binding, SourceBinding) or not isinstance(selection, Selection) or type(initial) is not bool:
        raise ModelError('Invalid reconciliation inputs')
    _binding(binding.canonical())
    if type(excluded_roots) is not tuple or len(excluded_roots) > 128:
        raise ModelError('Invalid explicit excluded roots')
    reader = _Reader()
    for root in excluded_roots:
        _absolute(root)
        try:
            for parent in (*reversed(root.parents), root):
                if reader.observe(parent, missing=True) is None:
                    break
        except OSError:
            raise OperationalError('Cannot validate explicit excluded root') from None
        left, right = unicodedata.normalize('NFC', str(root)).casefold(), unicodedata.normalize('NFC', str(vault)).casefold()
        if left == right or left.startswith(right + os.sep) or right.startswith(left + os.sep):
            raise ConflictError('Vault overlaps an explicit excluded root')
    try:
        reader.parents(vault)
        root_info = reader.observe(vault)
        if root_info is None or not stat.S_ISDIR(root_info.st_mode):
            raise ConflictError('Explicit vault is not a directory')
        # Use this reader for state too, so final scan checks include its observations.
        control = reader.observe(vault / '.obforce', missing=True)
        document = None
        if control is not None:
            if not stat.S_ISDIR(control.st_mode):
                raise ConflictError('Invalid state control directory')
            if reader.observe(state_path, missing=True) is not None:
                document = parse_state(reader.read(state_path, const.MAX_STATE_BYTES))
        if document is not None:
            require_same_source(document.binding, binding)
            if document.selection != selection:
                raise ConflictError('State selection changed; absence comparison is unsupported')
        pending, count = [vault], 0
        locations: dict[str, str] = {}
        files: dict[str, str] = {}
        observations: dict[str, ParsedNote] = {}
        directory_ids = set()
        while pending:
            directory = pending.pop()
            info = reader.observe(directory)
            identity = (info.st_dev, info.st_ino)
            if identity in directory_ids:
                raise ConflictError('Duplicate directory identity')
            directory_ids.add(identity)
            # Bound while iterating, before allocating/sorting a directory listing.
            children = []
            with os.scandir(directory) as entries:
                for entry in entries:
                    count += 1
                    if count > const.MAX_VAULT_ENTRIES:
                        raise ConflictError('Vault exceeds entry bound')
                    children.append(entry.name)
            for name in sorted(children):
                path = directory / name
                relative = path.relative_to(vault).as_posix()
                info = reader.observe(path)
                control_name = unicodedata.normalize('NFC', name).casefold()
                if control_name in const.CONTROL_DIRECTORIES:
                    if name != control_name:
                        raise ConflictError('Ambiguous control directory spelling')
                    continue
                token = _portable(relative)
                if token in locations:
                    raise ConflictError('Portable vault path collision')
                locations[token] = relative
                if stat.S_ISDIR(info.st_mode):
                    pending.append(path)
                else:
                    files[token] = relative
                    if path.suffix.casefold() != '.md':
                        continue
                    raw = reader.read(path, const.MAX_NOTE_BYTES)
                    if b'obforce' not in raw.lower() and b'sf_' not in raw.lower():
                        continue
                    try:
                        _path(relative)
                    except ConfigError:
                        raise ConflictError('Unsafe managed Markdown path') from None
                    parsed = parse_note(raw)
                    identity = parsed.properties['obforce_id']
                    if identity in observations:
                        raise ConflictError('Duplicate managed note identity')
                    observations[identity] = parsed
                    # Store the exact observed relative path separately from immutable parser bytes.
                    files['id:' + identity] = relative
        if document is None:
            if observations or not initial:
                raise ConflictError('Missing state cannot establish managed ownership')
            reader.finish()
            return Reconciliation(None, MappingProxyType({}), (), MappingProxyType({}), True)
        if observations.keys() != {saved.note.obforce_id for saved in document.notes}:
            raise ConflictError('Tracked notes vanished or untracked managed notes exist')
        saved_notes, changes, paths = [], [], {}
        for saved in document.notes:
            note = saved.note
            observed = observations[note.obforce_id]
            if observed.generated_properties != note.generated_properties or observed.region != saved.generated_region:
                raise ConflictError('Managed content differs from saved baseline')
            location = files['id:' + note.obforce_id]
            if note.path != location:
                old = unicodedata.normalize('NFC', note.path).casefold()
                # Any occupied old location (file or directory) makes ownership ambiguous.
                if old in locations and locations[old] != location:
                    raise ConflictError('Tracked old path is occupied')
                changes.append(PathChange(note.key, note.path, location))
            # A file occupying a future parent of a tracked old path is ambiguous too.
            if any(
                unicodedata.normalize('NFC', '/'.join(note.path.split('/')[:n])).casefold() in files
                for n in range(1, len(note.path.split('/')))
            ):
                raise ConflictError('Tracked path parent is occupied')
            saved_notes.append(SavedNote(replace(note, path=location), saved.generated_region))
            paths[note.key] = location
        candidate = replace(document, notes=tuple(saved_notes))
        serialize_state(candidate)  # Enforce the candidate output bound before returning it.
        reader.finish()
        return Reconciliation(candidate, MappingProxyType(paths), tuple(changes), MappingProxyType(observations), False)
    except UnicodeError:
        raise ConflictError('Unsupported vault path encoding') from None
    except OSError:
        raise OperationalError('Cannot complete explicit vault read') from None
